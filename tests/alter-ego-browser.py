"""Real browser interactions with isolated IndexedDB; no localhost or external service."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
from urllib.parse import urlparse, unquote
import json
ROOT=Path(__file__).resolve().parents[1]
BASE='https://production.test/habitkit-app/'
MIME={'.html':'text/html','.js':'text/javascript','.css':'text/css','.png':'image/png','.svg':'image/svg+xml','.webmanifest':'application/manifest+json'}
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    context=browser.new_context(viewport={'width':390,'height':844},service_workers='block',timezone_id='America/Araguaina',has_touch=True)
    errors=[]
    def serve(route):
        path=unquote(urlparse(route.request.url).path)
        assert path.startswith('/habitkit-app/')
        target=(ROOT/'dist'/(path.removeprefix('/habitkit-app/') or 'index.html')).resolve()
        assert target.is_relative_to(ROOT/'dist') and target.is_file(),path
        route.fulfill(status=200,content_type=MIME.get(target.suffix,'application/octet-stream'),body=target.read_bytes())
    context.route('**/*',serve)
    page=context.new_page()
    page.on('pageerror',lambda e:errors.append(str(e)))
    def action(name):return page.get_by_role('button',name=name,exact=True)
    def ego(key):return page.locator(f'[data-ego="{key}"]')
    def field(name):return page.locator(f'#alter-ego-root [name="{name}"]')
    def identity_data():
        return page.evaluate('''async()=>{const d=await new Promise((ok,no)=>{const r=indexedDB.open('habitkit-identity',1);r.onsuccess=()=>ok(r.result);r.onerror=no});return await new Promise((ok,no)=>{const r=d.transaction('workspace').objectStore('workspace').get('current');r.onsuccess=()=>ok(r.result);r.onerror=no})}''')
    page.goto(BASE)
    action('Criar meu primeiro hábito').click()
    page.locator('#habit-form [name=name]').fill('Ler todos os dias')
    action('Criar hábito').click()
    expect(page.locator('.habit-card')).to_have_count(1)
    assert page.locator('.tabbar button').all_text_contents()==['Hábitos','Estatísticas','Alter Ego','Ajustes']
    action('Alter Ego').click()
    expect(page.get_by_role('heading',name='My Alter Ego')).to_be_visible()
    page.screenshot(path='/tmp/alter-ego-welcome.png',full_page=True)
    action('Construir meu alter ego').click()
    field('name').fill('Minha versão confiante')
    field('description').fill('Uma mulher que age de acordo com seus valores.')
    field('statement').fill('Eu cumpro o que prometo a mim mesma.')
    action('Continuar →').click()
    page.locator('[name=traits][value="Confiante"]').check()
    page.locator('[name=traits][value="Disciplinada"]').check()
    field('customTrait').fill('Curiosa')
    action('Continuar →').click()
    page.locator('[name=values][value="Liberdade"]').check()
    field('customValue').fill('Gentileza')
    action('Continuar →').click()
    field('reflection-0').fill('Com leitura, água e uma intenção clara.')
    action('Salvar minha identidade →').click()
    expect(page.locator('.ae-profile-title h2')).to_have_text('Minha versão confiante')
    assert 'Curiosa' in page.locator('.ae-tags').inner_text()
    assert 'Gentileza' in page.locator('.ae-values').inner_text()
    action('Escolher capa').click()
    page.locator('#ae-cover-file').set_input_files(ROOT/'public/logo.png')
    expect(page.locator('img.ae-cover')).to_be_visible()
    page.reload()
    expect(action('Visualizar identidade')).to_be_visible()
    action('Visualizar identidade').click()
    expect(page.locator('img.ae-cover')).to_be_visible()
    action('Meu Moodboard').click()
    action('Criar meu Moodboard').click()
    expect(page.locator('.ae-canvas')).to_be_visible()
    ego('add-element').click()
    action('Adicionar frase').click()
    field('content').fill('Minha disciplina constrói minha liberdade.')
    action('Adicionar ao painel').click()
    expect(page.locator('.ae-element')).to_have_count(1)
    expect(field('x')).to_have_value('60')
    el=page.locator('.ae-element').first
    el.scroll_into_view_if_needed()
    box=el.bounding_box()
    page.mouse.move(box['x']+box['width']/2,box['y']+box['height']/2)
    page.mouse.down()
    page.mouse.move(box['x']+box['width']/2+28,box['y']+box['height']/2+35,steps=6)
    page.mouse.up()
    expect(field('x')).not_to_have_value('60')
    # Exercise actual touch pointer events as well as mouse input.
    old_x=field('x').input_value()
    el=page.locator('.ae-element').first
    el.scroll_into_view_if_needed()
    box=el.bounding_box()
    touch=context.new_cdp_session(page)
    x=box['x']+box['width']/2
    y=box['y']+box['height']/2
    touch.send('Input.dispatchTouchEvent',{'type':'touchStart','touchPoints':[{'x':x,'y':y,'id':1}]})
    touch.send('Input.dispatchTouchEvent',{'type':'touchMove','touchPoints':[{'x':x+18,'y':y+12,'id':1}]})
    touch.send('Input.dispatchTouchEvent',{'type':'touchEnd','touchPoints':[]})
    expect(field('x')).not_to_have_value(old_x)
    old_width=int(field('w').input_value())
    handle=page.locator('.ae-element.selected [data-resize]')
    handle.scroll_into_view_if_needed()
    box=handle.bounding_box()
    page.mouse.move(box['x']+16,box['y']+16)
    page.mouse.down()
    page.mouse.move(box['x']+40,box['y']+35,steps=5)
    page.mouse.up()
    page.wait_for_function(f"Number(document.querySelector('#ae-element-form [name=w]')?.value) > {old_width}")
    field('rotation').fill('8')
    field('color').fill('#c72d67')
    action('Aplicar alterações').click()
    expect(page.locator('.ae-element').first).to_have_attribute('style',__import__('re').compile('rotate\\(8deg\\)'))
    ego('add-element').click()
    action('Escolher da galeria / adicionar imagem').click()
    page.locator('#ae-image-file').set_input_files(ROOT/'public/logo.png')
    expect(page.locator('.ae-element')).to_have_count(2)
    assert page.locator('.ae-element img').evaluate('(im)=>im.complete && im.naturalWidth===1254')
    action('Trazer à frente').click()
    expect(page.locator('.ae-element.selected')).to_be_visible()
    action('Usar como capa').click()
    ego('new-category').click()
    field('name').fill('Viagens')
    action('Criar categoria').click()
    field('category').select_option('Viagens')
    action('Aplicar alterações').click()
    page.locator('#ae-category-filter').select_option('Viagens')
    expect(page.locator('.ae-element')).to_have_count(1)
    page.locator('#ae-category-filter').select_option('all')
    expect(page.locator('.ae-element')).to_have_count(2)
    page.locator('.ae-canvas').scroll_into_view_if_needed()
    page.screenshot(path='/tmp/alter-ego-board-mobile.png',full_page=True)
    with page.expect_download() as download:
        action('Exportar imagem').click()
    png='/tmp/alter-ego-test-export.png'
    download.value.save_as(png)
    assert Path(png).read_bytes().startswith(b'\x89PNG')
    action('Tela cheia').click()
    expect(page.locator('.ae-fullscreen')).to_be_visible()
    action('Sair da tela cheia').click()
    action('Personalizar painel').click()
    field('background').fill('#eee9e3')
    action('Salvar fundo').click()
    ego('board-menu').click()
    action('Duplicar painel').click()
    expect(page.locator('#ae-board-select option')).to_have_count(2)
    page.locator('.ae-element').last.click()
    ego('delete-element').click()
    action('Confirmar').click()
    expect(page.locator('.ae-element')).to_have_count(1)
    # Original composition survives reload and changing boards.
    page.reload()
    action('Alter Ego').click()
    action('Meu Moodboard').click()
    expect(page.locator('#ae-board-select option')).to_have_count(2)
    page.locator('#ae-board-select').select_option(index=0)
    expect(page.locator('.ae-element')).to_have_count(2)
    action('Minha versão futura').click()
    field('letter').fill('Querida eu, hoje você vive com coragem e constância.')
    action('30 dias').click()
    action('Salvar minha carta').click()
    expect(page.locator('[name=reviewDate]')).not_to_have_value('')
    action('Identidade em ação').click()
    action('+ Comportamento').click()
    field('name').fill('Leio antes de abrir as redes sociais')
    field('description').fill('Dez páginas com atenção.')
    field('trait').select_option('Disciplinada')
    field('habitId').select_option(label='Ler todos os dias')
    action('Salvar comportamento').click()
    expect(page.locator('.ae-behavior')).to_have_count(1)
    action('Criar meta').click()
    field('name').fill('Construir uma rotina de leitura')
    field('due').fill('2027-01-01')
    action('Salvar meta').click()
    expect(page.locator('.ae-goal')).to_have_count(1)
    assert 'Ler todos os dias' in page.locator('.ae-goal').inner_text()
    # Linked behavior opens the existing habit rather than a duplicate.
    ego('open-habit').click()
    expect(page.locator('.detail-identity h1')).to_have_text('Ler todos os dias')
    action('Voltar aos hábitos').click()
    action('Alter Ego').click()
    action('Minha versão futura').click()
    expect(field('letter')).to_have_value('Querida eu, hoje você vive com coragem e constância.')
    action('Minha identidade').click()
    with page.expect_download() as download:
        action('Exportar backup da identidade').click()
    backup='/tmp/alter-ego-test-backup.json'
    download.value.save_as(backup)
    original=json.loads(Path(backup).read_text())
    assert len(original['boards'])==2 and len(original['behaviors'])==1 and len(original['goals'])==1
    assert original['boards'][0]['elements'][1]['src'].startswith('data:image/png;base64,')
    for width in [320,390,768,1440]:
        page.set_viewport_size({'width':width,'height':900})
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'),width
    action('Meu Moodboard').click()
    for width in [320,390,768,1440]:
        page.set_viewport_size({'width':width,'height':900})
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'),width
    action('Minha identidade').click()
    action('Excluir minha identidade').click()
    action('Confirmar').click()
    expect(action('Construir meu alter ego')).to_be_visible()
    # Restore identity and images from portable backup.
    page.locator('#ae-restore-file').set_input_files(backup)
    action('Confirmar').click()
    expect(page.locator('.ae-profile-title h2')).to_have_text('Minha versão confiante')
    assert len(identity_data()['boards'])==2
    action('Hábitos').click()
    expect(page.locator('.habit-card')).to_have_count(1)
    # Complete app backup now includes both habits and IndexedDB identity.
    action('Ajustes').click()
    with page.expect_download() as download:
        page.get_by_role('button',name='Exportar backup',exact=False).click()
    fullbackup='/tmp/habitkit-complete-test-backup.json'
    download.value.save_as(fullbackup)
    bundle=json.loads(Path(fullbackup).read_text())
    assert bundle['alterEgo']['identity']['name']=='Minha versão confiante'
    assert len(bundle['habits'])==1
    page.locator('#backup-file').set_input_files(fullbackup)
    action('Restaurar dados').click()
    page.wait_for_function("JSON.parse(localStorage.habitkit).habits.length === 1")
    assert identity_data()['identity']['name']=='Minha versão confiante'
    # Older habits-only backups must not erase the new identity workspace.
    legacy=dict(bundle)
    legacy.pop('alterEgo')
    page.locator('#backup-file').set_input_files({'name':'legacy.json','mimeType':'application/json','buffer':json.dumps(legacy).encode()})
    action('Restaurar dados').click()
    expect(page.locator('#overlay')).to_be_empty()
    assert identity_data()['identity']['name']=='Minha versão confiante'
    assert not errors,errors
    print(json.dumps({'alter_ego':'passed','checks':['navigation order','identity onboarding','traits and custom values','persistent cover','image upload','pointer drag and resize','text styling','categories and filtering','layers','PNG export','fullscreen','background','duplicate and delete','IndexedDB reload','letter and review date','behavior linked to existing habit','goal linked to identity and habit','responsive widths','identity backup restore','complete app backup and restore','legacy backup compatibility'],'browser_errors':errors}))
    browser.close()
